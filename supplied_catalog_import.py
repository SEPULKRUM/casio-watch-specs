"""Convert a checked, user-supplied catalog transcription without inferring variants."""
import argparse
import hashlib
import json
from pathlib import Path
import specs

REFERENCE = 'research/supplied-casio-1983-catalog-2026-11-17.json'

def convert(batch, reference=REFERENCE):
    if batch.get('type') != 'supplied_catalog_visual_extraction':
        raise ValueError('Expected a supplied catalog transcription')
    if not reference.startswith('research/') or '..' in Path(reference).parts:
        raise ValueError('Research reference required')
    checksum = specs.digest(batch)
    def fact(value, locator, evidence):
        return {'value': value, 'uncertainty': 'Visually transcribed supplied catalog; not independently archive-verified. Exact printed model scope only.',
                'sources': [{'kind': 'user_provided', 'provided_by': batch['provided_by'],
                    'reference': reference, 'source_sha256': checksum, 'accessed': batch['received'],
                    'permission': 'user_provided', 'locator': locator, 'evidence': evidence}]}
    records = []
    unique = {}
    for row in batch['models']:
        unique.setdefault(row['model_id'], []).append(row)
    for occurrences in unique.values():
        row = occurrences[0]
        key = specs.identity(row['model_id'])
        location = f"{row['image']} / printed page {row['page'] if row['page'] is not None else 'back cover'} / {key} caption"
        values = {'module_id': row['module_id'], 'catalog_material_finish': row['material_caption'],
                  'reference_scope': row['reference_scope'],
                  'catalog_source_references': {'document_code': batch['document_code'], 'image': row['image'], 'printed_page': row['page']}}
        values['catalog_1983_evidence'] = {'category': 'watch', 'observations': occurrences}
        for name in ['water_resistance_m']:
            if name in row: values[name] = row[name]
        if row.get('family'): values['series'] = row['family']
        if row.get('dial_availability_note'): values['catalog_description'] = row['dial_availability_note']
        records.append({'kind': 'model', 'id': key, 'specs': {k: fact(v, location, f'{key}: {k} = {v}') for k, v in values.items()}})
    for row in batch['modules']:
        key = row['module_id']; location = 'Printed pages ' + ', '.join(map(str, row['pages'])) + f' / module {key} technical table'
        values = {k: row[k] for k in ['accuracy_seconds_per_month', 'battery_cell', 'battery_runtime', 'calendar', 'alarm_count', 'stopwatch', 'timer', 'thermometer', 'power_supply'] if k in row}
        values['catalog_1983_evidence'] = row
        records.append({'kind': 'module', 'id': key, 'specs': {k: fact(v, location, f'Module {key}: {k} = {v}') for k, v in values.items()}})
    for row in batch['clocks']:
        key = row['model_id']; location = f"{row['image']} / printed page 21 / {key} clock table"
        values = {'catalog_1983_evidence': row, 'series': 'Clocks', 'reference_scope': 'supplied_catalog_clock_index',
                  'catalog_description': row['facts'], 'catalog_source_references': {'printed_page':21,'image':row['image'],'scope':row['scope']}}
        records.append({'kind': 'model', 'id': key, 'specs': {k: fact(v, location, f'{key}: {k} = {v}') for k, v in values.items()}})
    plan = batch.get('application_plan')
    if plan is not None:
        for record in records:
            allowed = plan[record['kind'] + ':' + record['id']]
            record['specs'] = {k:v for k,v in record['specs'].items() if k in allowed}
            if 'catalog_1983_evidence' not in record['specs']: raise ValueError('Full scoped catalog evidence must be retained')
    for record in records: specs.validate(record)
    return records

def web_artifact(batch, reference=REFERENCE):
    """Publish only bounded technical transcriptions, never uploaded images."""
    records = convert(batch, reference)
    data = {'schema_version':1,'source_reference':reference,
        'source_sha256':specs.digest(batch),
        'source_file_sha256':hashlib.sha256(Path(reference).read_bytes()).hexdigest(),
        'received':batch['received'],'document_code':batch['document_code'],'date_scope':batch['date_scope'],
        'watch_identifiers':list(dict.fromkeys(r['model_id'] for r in batch['models'])),
        'clock_identifiers':[r['model_id'] for r in batch['clocks']],
        'identifier_occurrences':[r['model_id'] for r in batch['models']]+[r['model_id'] for r in batch['clocks']],
        'records':[{'kind':r['kind'],'id':r['id'],'specs':{k:v['value'] for k,v in r['specs'].items()}} for r in records],
        'service_reference':batch['service_reference'],'discrepancies':batch['discrepancies']}
    return ('// Technical transcription only; supplied scans are not distributed. Generated by supplied_catalog_import.py.\n'
            'export const catalog1983='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source'); parser.add_argument('--output', required=True)
    parser.add_argument('--web-output')
    args = parser.parse_args()
    specs.write(args.output, convert(specs.load(args.source), args.source))
    if args.web_output:
        Path(args.web_output).write_text(web_artifact(specs.load(args.source), args.source))
